#!/usr/bin/env python3
"""Generate Vondrak pole coefficients from the pinned, unmodified ERFA sources."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Scripts/orientation-data/long-term'
OUTPUT = ROOT / 'Sources/AstronomyKit/Engine/Orientation/Generated/Vondrak2011Terms.swift'


def coefficients(name, prefix):
    text = (SOURCE / name).read_text()
    result = []
    for suffix in ('pol', 'per'):
        body = re.search(r'\b' + prefix + suffix + r'\[.*?=\s*\{(.*?)\n   \};', text, re.S).group(1)
        result.append([re.findall(r'[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?', row)
                       for row in re.findall(r'\{([^{}]+)\}', body)])
    return result


def generate():
    manifest = json.loads((SOURCE / 'manifest.json').read_text())
    for name, item in manifest['files'].items():
        path = SOURCE / name
        if hashlib.sha256(path.read_bytes()).hexdigest() != item['sha256']:
            raise ValueError(f'Pinned source changed: {path}')
    lines = ['// Generated by Scripts/generate-long-term-precession.py; do not edit.',
             '// Vondrak, Capitaine & Wallace (2011), with the 2012 corrigendum.',
             '// ERFA v2.0.1, commit 9915ba38c9365f8b0738269b8c2ac1fdd5f8dee3.',
             '// ERFA-derived coefficients: see THIRD_PARTY_NOTICES and the archived source licenses.',
             '', 'extension Engine.Precession {']
    for name, prefix, label in [('ltpecl.c', 'pq', 'ecliptic'), ('ltpequ.c', 'xy', 'equator')]:
        for rows, suffix in zip(coefficients(name, prefix), ('Polynomial', 'Periodic')):
            lines.append(f'    static let {label}{suffix}: [[Double]] = [')
            lines.extend('        [' + ', '.join(row) + '],' for row in rows)
            lines.append('    ]')
    lines.extend(['}', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        if OUTPUT.read_text() != output:
            raise SystemExit(f'Stale generated file: {OUTPUT}')
        print('Long-term precession coefficients match pinned ERFA sources.')
    else:
        OUTPUT.write_text(output)
