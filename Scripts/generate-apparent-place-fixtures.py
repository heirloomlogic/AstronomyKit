#!/usr/bin/env python3
"""Pin ERFA values and independent 80-digit directional derivatives."""
import argparse
import ctypes
import hashlib
import json
import math
from pathlib import Path
import re
import subprocess
import tempfile
import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Scripts/apparent-place-data'
OUTPUT = ROOT / 'Tests/AstronomyKitTests/Engine/Positions/PublishedApparentPlace.swift'
mp.mp.dps = 80
SRS = mp.mpf('1.97412574336e-8')


def dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def cross(a, b):
    return [a[(i+1)%3]*b[(i+2)%3]-a[(i+2)%3]*b[(i+1)%3] for i in range(3)]


def unit(a):
    length = mp.sqrt(dot(a, a))
    return [x/length for x in a]


def moving(v, d, t):
    return [mp.mpf(x)+t*mp.mpf(y) for x, y in zip(v, d)]


def direction(seed, rate):
    p = [float(v) for v in unit(seed)]
    d = [float(rate[i]-p[i]*dot(p, rate)) for i in range(3)]
    return p, d


def aberration(p, v, s):
    bm1 = mp.sqrt(1-dot(v, v))
    pdv = dot(p, v)
    return unit([p[i]*bm1+(1+pdv/(1+bm1))*v[i]+SRS/s*(v[i]-pdv*p[i]) for i in range(3)])


def deflection(p, q, e, mass, distance, limiter):
    w = mass*SRS/distance/max(dot(q, [q[i]+e[i] for i in range(3)]), limiter)
    correction = cross(p, cross(e, q))
    return [p[i]+w*correction[i] for i in range(3)]


def tdb_model():
    source = (SOURCE/'dtdb.c').read_text()
    body = source.split('static const double fairhd[787][3] = {')[1].split('};')[0]
    terms = [[mp.mpf(x.strip()) for x in row.split(',')] for row in re.findall(r'\{([^{}]+)\}', body)]
    if len(terms) != 787:
        raise ValueError('Fairhead source shape changed')
    def offset(tt):
        t = tt/mp.mpf(365250)
        values = []
        for lo, hi in [(0,474),(474,679),(679,764),(764,784),(784,787)]:
            values.append(mp.fsum(a*mp.sin(b*t+c) for a,b,c in terms[lo:hi]))
        value = mp.fsum(v*t**i for i,v in enumerate(values))
        for a,b,c in [('0.00065e-6','6069.776754','4.021194'),('0.00033e-6','213.299095','5.543132'),
                      ('-0.00196e-6','6208.294251','5.696701'),('-0.00173e-6','74.781599','2.435900')]:
            value += mp.mpf(a)*mp.sin(mp.mpf(b)*t+mp.mpf(c))
        return value+mp.mpf('0.03638e-6')*t*t
    return offset


def swift(v):
    if isinstance(v, (list, tuple)):
        return 'SIMD3(' + ', '.join(repr(float(x)) for x in v) + ')'
    return repr(float(v))


def generate():
    manifest = json.loads((SOURCE/'manifest.json').read_text())
    for name, entry in manifest['files'].items():
        if hashlib.sha256((SOURCE/name).read_bytes()).hexdigest() != entry['sha256']:
            raise ValueError('Archived ERFA source changed: '+name)
    lines = ['// Generated by Scripts/generate-apparent-place-fixtures.py; do not edit.',
             '// Values: pinned ERFA C. Rates: independent 80-digit Python formulas.',
             'enum PublishedApparentPlace {',
             '    struct Aberration {',
             '        let p, dp, beta, dbeta: SIMD3<Double>',
             '        let distance, distanceRate: Double',
             '        let expected, expectedRate: SIMD3<Double>', '    }',
             '    struct Deflection {',
             '        let p, dp, q, dq, e, de: SIMD3<Double>',
             '        let mass, distance, distanceRate, limiter, limiterRate: Double',
             '        let expected, expectedRate: SIMD3<Double>', '    }',
             '    struct Retarded {', '        let tt, emission, emissionRate, displacementRate, delay, ttOnlyEmission: Double', '    }']
    vector = ctypes.c_double*3
    with tempfile.TemporaryDirectory() as tmp:
        library = Path(tmp)/'erfa.so'
        subprocess.run(['cc', '-shared', '-fPIC', '-O2', '-o', str(library),
                        *[str(SOURCE/(f+'.c')) for f in ['ab','ld','pdp','pxp','dtdb']], '-lm'], check=True)
        erfa = ctypes.CDLL(str(library))
        erfa.eraAb.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_double, ctypes.c_double, ctypes.c_void_p]
        erfa.eraLd.argtypes = [ctypes.c_double, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p,
                              ctypes.c_double, ctypes.c_double, ctypes.c_void_p]
        lines.append('    static let aberration: [Aberration] = [')
        for i, speed in enumerate([0, 1e-6, 1e-4, 0.1, 0.5]):
            p, dp = direction([1+i, -2, 3-i], [0.03, -0.02, 0.01])
            beta = [speed, -speed/3, speed/4]
            dbeta = [1e-6, 3e-7, -8e-7]
            distance, ds = 0.9+i, -0.003+i*0.001
            out = vector()
            erfa.eraAb(vector(*p),vector(*beta),distance,math.sqrt(1-dot(beta,beta)),out)
            def function(t):
                return aberration(moving(p,dp,t),moving(beta,dbeta,t),mp.mpf(distance)+t*mp.mpf(ds))
            rates = [mp.diff(lambda t: function(t)[j], 0) for j in range(3)]
            lines.append('        Aberration('+', '.join(f'{k}: {swift(v)}' for k,v in
                [('p',p),('dp',dp),('beta',beta),('dbeta',dbeta),('distance',distance),('distanceRate',ds),
                 ('expected',list(out)),('expectedRate',rates)])+'),')
        lines += ['    ]', '    static let deflection: [Deflection] = [']
        for i, limit in enumerate([1e-10, 0.01, 1, 3]):
            p,dp = direction([-1,0.01+i*0.2,0.3], [0.01,0.02,-0.01])
            q,dq = direction([-1,0.02+i*0.1,0.1], [0.03,-0.01,0.02])
            e,de = direction([1,0.01,0.03], [-0.01,0.01,0.01])
            mass,distance,ds,dl = 1.0,1.2,-0.001,limit*0.002
            out=vector()
            erfa.eraLd(mass,vector(*p),vector(*q),vector(*e),distance,limit,out)
            def function(t):
                return deflection(moving(p,dp,t),moving(q,dq,t),moving(e,de,t),mp.mpf(mass),
                                  mp.mpf(distance)+t*mp.mpf(ds),mp.mpf(limit)+t*mp.mpf(dl))
            rates=[mp.diff(lambda t: function(t)[j],0) for j in range(3)]
            lines.append('        Deflection('+', '.join(f'{k}: {swift(v)}' for k,v in
                [('p',p),('dp',dp),('q',q),('dq',dq),('e',e),('de',de),('mass',mass),('distance',distance),
                 ('distanceRate',ds),('limiter',limit),('limiterRate',dl),('expected',list(out)),('expectedRate',rates)])+'),')
        lines += ['    ]', '    static let retarded: [Retarded] = [']
        offset = tdb_model()
        c = mp.mpf(299792458)*86400/mp.mpf(149597870700)
        vo, vt = mp.mpf('0.01'), mp.mpf('0.02')
        erfa.eraDtdb.argtypes = [ctypes.c_double]*6
        erfa.eraDtdb.restype = ctypes.c_double
        for epoch in [-1461000, -1000, 0, 100, 36525.25, 1461000]:
            tt = mp.mpf(epoch)
            # This Newton root uses the independently parsed original decimal ERFA table.
            root = mp.findroot(lambda emission: tt-emission+(offset(tt)-offset(emission))/86400
                               -(10+vt*(emission-tt))/c, (tt-mp.mpf('.1'),tt))
            # Independently compiled C provides a binary64 source consistency check.
            native = erfa.eraDtdb(2451545.0, float(tt), 0, 0, 0, 0)
            if abs(mp.mpf(native)-offset(tt)) > mp.mpf('1e-13'):
                raise ValueError('Independent TDB formula differs from archived ERFA')
            rate = (1+mp.diff(offset,tt)/86400+vo/c)/(1+mp.diff(offset,root)/86400+vt/c)
            delay = (10+vt*(root-tt))/c
            tt_only = tt-10/(c+vt)
            rows=[('tt',tt),('emission',root),('emissionRate',rate),('displacementRate',vt*rate-vo),
                  ('delay',delay),('ttOnlyEmission',tt_only)]
            lines.append('        Retarded('+', '.join(f'{k}: {swift(v)}' for k,v in rows)+'),')
        lines += ['    ]','}','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    generated=generate()
    if args.check:
        current=OUTPUT.read_text()
        # Formatting is independent of the generated structure; C/libm may differ in the last bits.
        pattern=r'(?<![A-Za-z_])[+-]?(?:\d+\.\d*|\d*\.\d+)(?:[eE][+-]?\d+)?'
        if re.sub(r'\s+','',re.sub(pattern,'NUMBER',current)) != re.sub(r'\s+','',re.sub(pattern,'NUMBER',generated)):
            raise ValueError('Generated fixture structure changed')
        a,b=re.findall(pattern,current),re.findall(pattern,generated)
        if len(a)!=len(b) or any(abs(float(x)-float(y))>max(5e-15,2*math.ulp(float(y))) for x,y in zip(a,b)):
            raise ValueError('Generated fixture values changed')
        print('Verified eight ERFA sources, nine value/rate fixtures and six TDB light-time roots')
    else:
        OUTPUT.write_text(generated)


if __name__=='__main__':
    main()
