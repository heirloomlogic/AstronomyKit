#!/usr/bin/env python3
"""Build the archived ERFA C oracle and capture unbiased and biased matrices."""
import argparse
import ctypes
import importlib.util
import math
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Scripts/orientation-data/long-term'
OUTPUT = ROOT / 'Tests/AstronomyKitTests/Engine/Orientation/PublishedLongTermPrecession.swift'
spec = importlib.util.spec_from_file_location('coefficients', ROOT / 'Scripts/generate-long-term-precession.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def generate():
    module.generate()  # Verify every archived source against its manifest.
    orientation = (ROOT / 'Tests/AstronomyKitTests/Engine/Orientation/PublishedOrientation.swift').read_text()
    epochs = [float(s.replace('_', '')) for s in re.findall(r'\btt: ([-\d_.]+),', orientation)]
    epochs += [-1461000.0, -1460999.9999999998, -1095750.0, -730500.0, -365250.0,
               (1666.666 - 2000) * 365.25, 0.0, 365250.0, 730500.0, 1095750.0, 1460999.9999999998, 1461000.0,
               53736.0 - 51544.5]
    epochs = sorted(set(epochs))
    vector = ctypes.c_double * 3
    matrix = vector * 3
    lines = ['// Generated by Scripts/generate-long-term-precession-fixtures.py; do not edit.',
             '// Independently compiled, unmodified ERFA v2.0.1 C sources; see the pinned source manifest.',
             '', 'enum PublishedLongTermPrecession {',
             '    struct Reference: Sendable {', '        let tt: Double',
             '        let matrix: [[Double]]', '        let biasedMatrix: [[Double]]',
             '        let meanObliquity: Double', '    }',
             '    static let references: [Reference] = [']
    with tempfile.TemporaryDirectory() as tmp:
        library = Path(tmp) / 'erfa.so'
        files = ['ltp', 'ltpb', 'ltpecl', 'ltpequ', 'pxp', 'pn', 'pm', 'sxp', 'zp']
        subprocess.run(['cc', '-shared', '-fPIC', '-O2', '-o', str(library),
                        *[str(SOURCE / (f + '.c')) for f in files], '-lm'], check=True)
        erfa = ctypes.CDLL(str(library))
        for fn in ['eraLtp', 'eraLtpb', 'eraLtpecl', 'eraLtpequ']:
            getattr(erfa, fn).argtypes = [ctypes.c_double, ctypes.c_void_p]
        for tt in epochs:
            epoch = 2000 + tt / 365.25
            m, b, ecl, equ = matrix(), matrix(), vector(), vector()
            erfa.eraLtp(epoch, m)
            erfa.eraLtpb(epoch, b)
            erfa.eraLtpecl(epoch, ecl)
            erfa.eraLtpequ(epoch, equ)
            cross = [equ[(i+1)%3]*ecl[(i+2)%3] - equ[(i+2)%3]*ecl[(i+1)%3] for i in range(3)]
            epsilon = math.atan2(math.sqrt(sum(x*x for x in cross)), sum(a*b for a,b in zip(equ,ecl)))
            lines += [f'        Reference(tt: {tt!r},', '            matrix: [']
            lines += ['                [' + ', '.join(repr(x) for x in row) + '],' for row in m]
            lines += ['            ], biasedMatrix: [']
            lines += ['                [' + ', '.join(repr(x) for x in row) + '],' for row in b]
            lines += [f'            ], meanObliquity: {epsilon!r}),']
    lines += ['    ]', '', '    static func at(_ tt: Double) -> Reference {',
              '        references.first { $0.tt == tt }!', '    }', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        # libm rounding can vary by platform. Compare numbers at a tighter
        # tolerance than the Swift fixture checks, and preserve fixture text.
        numeric = r'(?<![\w.])[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?'
        old = OUTPUT.read_text()
        left, right = re.findall(numeric, old), re.findall(numeric, generated)
        if len(left) != len(right) or any(abs(float(a)-float(b)) > 5e-16 for a,b in zip(left,right)):
            raise SystemExit('Archived ERFA fixture values changed')
        print('Long-term precession fixtures match the archived ERFA C oracle.')
    else:
        OUTPUT.write_text(generated)
